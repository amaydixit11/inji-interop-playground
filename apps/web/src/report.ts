import type { RunRecord } from '@interop/shared';
import { CREDENTIAL_FORMAT_LABELS, STEP_LABELS, explainExchange } from '@interop/shared';

/**
 * A single run as a self-contained Markdown report.
 *
 * Written to be pasted into a bug report by someone who was not watching the
 * run: it carries the configuration, every assertion with the clause it cites,
 * and the exchanges that produced them. Deliberately provoked failures are
 * labelled so a reader does not mistake a passing negative test for a defect.
 */
export function runReport(run: RunRecord): string {
  const lines: string[] = [];
  const push = (...values: string[]) => lines.push(...values);
  const summary = run.summary;

  push(`# Interoperability run — ${run.status}`, '');
  push(`\`${run.id}\` · ${new Date(run.startedAt).toISOString()}`, '');

  push('## Configuration', '', '| | |', '| --- | --- |');
  push(`| Issuer | ${run.participants.issuer.label} (${run.participants.issuer.kind}) |`);
  push(`| Wallet | ${run.participants.wallet.label} (${run.participants.wallet.kind}) |`);
  push(`| Verifier | ${run.participants.verifier.label} (${run.participants.verifier.kind}) |`);
  push(`| Format | ${CREDENTIAL_FORMAT_LABELS[run.config.format]} (\`${run.config.format}\`) |`);
  push(`| Proof suite | \`${run.config.proofType}\` |`);
  push(`| OpenID4VCI revision | \`${run.config.vciDraft ?? 'draft-13'}\` |`);
  push(`| Presentation flow | \`${run.config.flowMode ?? 'cross-device'}\` |`);
  push(`| Fault injected | \`${run.config.tamper}\` |`);
  push(`| Traceability | ${run.traceability} |`);
  if (summary) {
    push(
      `| Result | ${summary.checksPassed} passed · ${summary.checksFailed} failed · ${summary.checksWarned} warned · ${summary.checksExpectedFailures} expected failure(s) |`,
    );
    push(`| Duration | ${summary.durationMs}ms |`);
  }
  push('');

  if (run.traceability === 'endpoint-only') {
    push(
      '> This run involved a participant the playground cannot observe directly, so some exchanges',
      '> are not captured. Endpoint behaviour is verified; the off-box participant’s own conformance is not.',
      '',
    );
  }

  if (summary?.failure) {
    push('## What stopped the run', '');
    push(`**${STEP_LABELS[summary.failure.step]}** — ${summary.failure.message}`);
    if (summary.failure.attributedTo) push('', `Attributed to the **${summary.failure.attributedTo}**.`);
    push('');
  }

  const problems = run.checks.filter((check) => check.status === 'fail' || check.status === 'warn');
  if (problems.length > 0) {
    push('## Findings', '');
    for (const check of problems) {
      const label = check.expected ? 'expected failure' : check.status;
      push(`### ${check.title} — \`${label}\``, '');
      push(check.detail, '');
      push(`*${check.spec}* · ${STEP_LABELS[check.step]}${check.attributedTo ? ` · attributed to the ${check.attributedTo}` : ''}`, '');
    }
  }

  push('## All assertions', '', '| Result | Check | Clause |', '| --- | --- | --- |');
  for (const check of run.checks) {
    const label = check.expected && check.status === 'fail' ? 'expected' : check.status;
    push(`| ${label} | ${check.title} | ${check.spec} |`);
  }
  push('');

  push('## Exchanges', '');
  for (const [index, exchange] of run.exchanges.entries()) {
    const status = exchange.error ? 'not captured' : String(exchange.status);
    push(`### ${index + 1}. ${exchange.label} — ${status}`, '');
    push(`\`${exchange.method} ${exchange.url}\` · ${exchange.from} → ${exchange.to}`, '');
    const explanation = explainExchange(exchange.label);
    if (explanation) push(`> ${explanation.what}`, '');
    if (exchange.error) push(`> ${exchange.error}`, '');
    if (exchange.requestBody !== undefined) {
      push('Request:', '', '```json', truncate(format(exchange.requestBody)), '```', '');
    }
    if (exchange.responseBody !== undefined) {
      push('Response:', '', '```json', truncate(format(exchange.responseBody)), '```', '');
    }
  }

  push('---', '', 'Generated by the Inji Interoperability Playground.', '');
  return lines.join('\n');
}

function format(value: unknown): string {
  if (typeof value === 'string') {
    try {
      return JSON.stringify(JSON.parse(value), null, 2);
    } catch {
      return value;
    }
  }
  return JSON.stringify(value, null, 2);
}

/** Keeps a report readable when a payload is a multi-kilobyte credential. */
function truncate(text: string, max = 4000): string {
  return text.length <= max ? text : `${text.slice(0, max)}\n… ${text.length - max} more characters`;
}

/** Offers a generated file to the browser as a download. */
export function download(filename: string, contents: string, type = 'text/markdown'): void {
  const url = URL.createObjectURL(new Blob([contents], { type }));
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}
